class NodeError(Exception):
    pass


class NodeSSH:
    def __init__(self, keyfile, known_hosts):
        self.keyfile, self.known_hosts = keyfile, known_hosts

    def ensure_key(self):
        if not os.path.exists(self.keyfile):
            subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", "storwize-panel",
                            "-f", self.keyfile], check=True)
        return open(self.keyfile + ".pub").read().strip()

    # --- host key (TOFU, confirmed by the admin in the UI) --------------
    @staticmethod
    def probe_hostkey(ip):
        t = paramiko.Transport((ip, 22))
        t.banner_timeout = 15
        try:
            t.start_client(timeout=15)
            k = t.get_remote_server_key()
        finally:
            t.close()
        import base64
        import hashlib
        fp = "SHA256:" + base64.b64encode(hashlib.sha256(k.asbytes()).digest()).decode().rstrip("=")
        return {"type": k.get_name(), "key": k.get_base64(), "fingerprint": fp}

    def _hostkeys(self):
        hk = paramiko.HostKeys()
        if os.path.exists(self.known_hosts):
            hk.load(self.known_hosts)
        return hk

    def trust(self, ip, password, hostkey):
        """Install the panel key on the node with the root password (once)."""
        pub = self.ensure_key()
        c = paramiko.SSHClient()
        hk = self._hostkeys()
        key = paramiko.PKey.from_type_string(hostkey["type"], __import__("base64").b64decode(hostkey["key"]))
        hk.add(ip, hostkey["type"], key)
        hk.save(self.known_hosts)
        c.load_host_keys(self.known_hosts)
        c.set_missing_host_key_policy(paramiko.RejectPolicy())
        try:
            c.connect(ip, username="root", password=password, look_for_keys=False,
                      allow_agent=False, timeout=15)
        except paramiko.AuthenticationException:
            raise NodeError("wrong root password")
        # /root/.ssh/authorized_keys is a symlink to /etc/pve/priv/authorized_keys on PVE
        cmd = ("f=/root/.ssh/authorized_keys; mkdir -p /root/.ssh; touch $f; "
               f"grep -qxF {sh(pub)} $f || echo {sh(pub)} >> $f")
        self._exec(c, cmd)
        c.close()

    def connect(self, ip):
        if not os.path.exists(self.keyfile):
            raise NodeError("node not authorized yet")
        c = paramiko.SSHClient()
        c.load_host_keys(self.known_hosts)
        c.set_missing_host_key_policy(paramiko.RejectPolicy())
        try:
            c.connect(ip, username="root", key_filename=self.keyfile, look_for_keys=False,
                      allow_agent=False, timeout=15)
        except paramiko.SSHException as e:
            raise NodeError(f"SSH: {e}")
        return c

    @staticmethod
    def _exec(c, cmd, timeout=600):
        _, out, err = c.exec_command(cmd, timeout=timeout)
        o, e = out.read().decode(errors="replace"), err.read().decode(errors="replace")
        rc = out.channel.recv_exit_status()
        return rc, o, e

    def run(self, ip, cmd, timeout=600):
        c = self.connect(ip)
        try:
            return self._exec(c, cmd, timeout)
        finally:
            c.close()

    def put(self, ip, path, content, mode=0o644):
        c = self.connect(ip)
        try:
            sftp = c.open_sftp()
            tmp = path + ".swpanel.tmp"
            with sftp.file(tmp, "w") as f:
                f.write(content)
            sftp.chmod(tmp, mode)
            sftp.posix_rename(tmp, path)
            sftp.close()
        finally:
            c.close()

    def status(self, ip):
        rc, o, e = self.run(ip, STATUS_SCRIPT, 60)
        try:
            d = json.loads(o)
        except ValueError:
            raise NodeError(f"invalid status: {e or o[:200]}")
        d["multipath_has_2145"] = '"2145"' in d["multipath_conf"]
        d["lvm_filter_ok"] = "36005076" in d.get("lvm_filter", "")
        return d

    @staticmethod
    def multipath_diff(current):
        return "".join(difflib.unified_diff(current.splitlines(True), MULTIPATH_CONF.splitlines(True),
                                            "/etc/multipath.conf (current)", "/etc/multipath.conf (new)"))


# Rejects IBM Storage Virtualize volumes (UID 6005076...) in the host LVM: the
# guests' own LVM must never be scanned or activated by the Proxmox node.
LVM_FILTER_SCRIPT = r"""python3 - <<'PYEOF'
import re, shutil, time, sys
p = "/etc/lvm/lvm.conf"
s = open(p).read()
add = ['"r|/dev/mapper/36005076.*|"', '"r|/dev/disk/by-id/dm-uuid-.*mpath-36005076.*|"', '"r|/dev/disk/by-id/dm-name-36005076.*|"',
       '"r|/dev/disk/by-id/scsi-36005076.*|"', '"r|/dev/disk/by-id/wwn-0x6005076.*|"']
m = re.search(r'^(\s*)global_filter\s*=\s*\[(.*?)\]', s, re.M | re.S)
if m and "36005076" in m.group(2):
    print("filter already present"); sys.exit(0)
shutil.copy2(p, p + ".bak." + time.strftime("%Y%m%d-%H%M%S"))
if m:
    items = [x.strip() for x in m.group(2).split(",") if x.strip()]
    new = m.group(1) + "global_filter=[" + ",".join(items + add) + "]"
    s = s[:m.start()] + new + s[m.end():]
else:
    s = re.sub(r"^devices\s*\{", "devices {\n\tglobal_filter=[" + ",".join(add) + "]", s, count=1, flags=re.M)
open(p, "w").write(s)
print("filter applied")
PYEOF
lvmconfig devices/global_filter && update-initramfs -u -k all >/dev/null 2>&1; echo initramfs updated"""


